-- Identificadores externos para sincronizar con otras herramientas (de momento,
-- NW Scheduler, que importa los movimientos desde un CSV).
--
-- - territories.external_id: id del territorio en la herramienta externa
--   (NW Scheduler: TerritoryID).
-- - persons.external_id: id de la persona en la herramienta externa
--   (NW Scheduler: PersonID). Informativo; NW Scheduler empareja por nombre.
-- - persons.external_name: nombre exacto con el que la herramienta externa
--   identifica a la persona (NW Scheduler: DisplayName). Se guarda tal cual, sin
--   recortar espacios, porque NW Scheduler exige coincidencia exacta.
-- - external_exports: registro de cada exportación (quién, cuándo, qué rango y
--   cuántas filas), para proponer el inicio de la siguiente y auditar.
--
-- Las columnas son opcionales y únicas dentro de la congregación. Ninguna vista ni
-- RPC existente cambia: las vistas listan columnas explícitas.

alter table public.territories
  add column if not exists external_id text;

alter table public.persons
  add column if not exists external_id text,
  add column if not exists external_name text;

alter table public.territories
  drop constraint if exists territories_external_id_not_blank;
alter table public.territories
  add constraint territories_external_id_not_blank
  check (external_id is null or length(btrim(external_id)) > 0);

alter table public.persons
  drop constraint if exists persons_external_id_not_blank;
alter table public.persons
  add constraint persons_external_id_not_blank
  check (external_id is null or length(btrim(external_id)) > 0);

alter table public.persons
  drop constraint if exists persons_external_name_not_blank;
alter table public.persons
  add constraint persons_external_name_not_blank
  check (external_name is null or length(btrim(external_name)) > 0);

create unique index if not exists territories_congregation_external_id_unique
  on public.territories (congregation_id, external_id)
  where external_id is not null;

create unique index if not exists persons_congregation_external_id_unique
  on public.persons (congregation_id, external_id)
  where external_id is not null;

create unique index if not exists persons_congregation_external_name_unique
  on public.persons (congregation_id, external_name)
  where external_name is not null;

-- ---------------------------------------------------------------------------
-- Registro de exportaciones

create table if not exists public.external_exports (
  id integer generated by default as identity primary key,
  congregation_id uuid not null references public.congregations(id) on delete cascade,
  exported_by uuid not null references public.profiles(id) on delete restrict,
  exported_at timestamptz not null default now(),
  range_start timestamptz not null,
  range_end timestamptz not null,
  row_count integer not null default 0,
  skipped_count integer not null default 0,
  constraint external_exports_range_valid check (range_start <= range_end),
  constraint external_exports_counts_valid check (row_count >= 0 and skipped_count >= 0)
);

create index if not exists external_exports_congregation_exported_at_idx
  on public.external_exports (congregation_id, exported_at desc);

create index if not exists external_exports_exported_by_idx
  on public.external_exports (exported_by);

alter table public.external_exports enable row level security;

-- Solo lectura para los administradores de la congregación activa. Las filas las
-- inserta la edge function con service_role.
drop policy if exists "external exports admin read" on public.external_exports;
create policy "external exports admin read"
on public.external_exports for select
to authenticated
using (
  congregation_id = public.current_congregation_id()
  and public.is_admin()
);

revoke all on public.external_exports from anon, public;
grant select on public.external_exports to authenticated;
grant all on public.external_exports to service_role;

create or replace function public.get_territory_statistics(territory_id integer)
returns jsonb
language plpgsql
stable
security invoker
set search_path = public
as $$
declare
  v_exists boolean;
  v_total integer;
  v_usage_rank integer;
  v_usage_count integer;
  v_avg_holding numeric;
  v_unique_persons integer;
begin
  perform public.require_authenticated();

  select exists(select 1 from public.territories where id = territory_id) into v_exists;
  if not v_exists then
    raise exception 'TERRITORY_NOT_FOUND' using errcode = 'P0002';
  end if;

  select count(*) into v_total from public.territories where archived = false;

  with usage as (
    select
      t.id,
      count(tt.id) as usage_count,
      dense_rank() over (order by count(tt.id) desc) as usage_rank
    from public.territories t
    left join public.territory_transactions tt on tt.territory_id = t.id
    where t.archived = false
    group by t.id
  )
  select usage_rank, usage_count
  into v_usage_rank, v_usage_count
  from usage
  where id = territory_id;

  select avg(extract(epoch from (picked_at - given_at)) / 86400.0)
  into v_avg_holding
  from public.territory_transactions
  where territory_id = get_territory_statistics.territory_id
    and picked_at is not null;

  select count(distinct person_id)
  into v_unique_persons
  from public.territory_transactions
  where territory_id = get_territory_statistics.territory_id;

  return jsonb_build_object(
    'totalTerritories', v_total,
    'usageRank', coalesce(v_usage_rank, v_total),
    'usageCount', coalesce(v_usage_count, 0),
    'averageHoldingTime', v_avg_holding,
    'uniqueUsersCount', coalesce(v_unique_persons, 0),
    'isHighUsage', coalesce(v_usage_rank, v_total) <= greatest(1, ceil(v_total * 0.25)),
    'isLowUsage', coalesce(v_usage_rank, v_total) > ceil(v_total * 0.75)
  );
end;
$$;

create or replace function public.get_action_logs(
  page_number integer default 1,
  page_size integer default 20,
  sort_field text default 'DateUtc',
  sort_order text default 'desc'
)
returns jsonb
language plpgsql
stable
security invoker
set search_path = public
as $$
declare
  v_total integer;
  v_offset integer := greatest(page_number - 1, 0) * greatest(page_size, 1);
  v_data jsonb;
begin
  perform public.require_superadmin();

  select count(*) into v_total from public.action_logs;

  with rows as (
    select
      al.action_type as "actionType",
      al.created_at as "dateUtc",
      al.message as "message",
      p.username as "userName",
      al.successful as "successful"
    from public.action_logs al
    join public.profiles p on p.id = al.user_id
    order by
      case when sort_field = 'ActionType' and lower(sort_order) = 'asc' then al.action_type end asc,
      case when sort_field = 'ActionType' and lower(sort_order) <> 'asc' then al.action_type end desc,
      case when sort_field = 'UserName' and lower(sort_order) = 'asc' then p.username end asc,
      case when sort_field = 'UserName' and lower(sort_order) <> 'asc' then p.username end desc,
      case when sort_field = 'Message' and lower(sort_order) = 'asc' then al.message end asc,
      case when sort_field = 'Message' and lower(sort_order) <> 'asc' then al.message end desc,
      case when sort_field = 'Successful' and lower(sort_order) = 'asc' then al.successful end asc,
      case when sort_field = 'Successful' and lower(sort_order) <> 'asc' then al.successful end desc,
      case when lower(sort_order) = 'asc' then al.created_at end asc,
      case when lower(sort_order) <> 'asc' then al.created_at end desc
    limit greatest(page_size, 1)
    offset v_offset
  )
  select coalesce(jsonb_agg(to_jsonb(rows)), '[]'::jsonb)
  into v_data
  from rows;

  return jsonb_build_object(
    'data', v_data,
    'totalCount', v_total,
    'pageNumber', page_number,
    'pageSize', page_size
  );
end;
$$;


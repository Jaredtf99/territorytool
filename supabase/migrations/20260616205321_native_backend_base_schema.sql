  t.id,
  t.code,
  t.name,
  t.map_url,
  t.image_path,
  t.archived,
  open_tx.id as active_transaction_id,
  open_tx.person_id,
  p.name as person_name,
  open_tx.given_at,
  last_picked.last_picked_at
